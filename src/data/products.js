function slug(str) {
  return str
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

export const PRODUCTS = Object.entries(RAW).flatMap(([category, items]) =>
  items.map(([name, unit, price, allergens = [], tags = []]) => ({
    id: `${slug(category)}-${slug(name)}`,
    name,
    category,
    unit,
    price,
    allergens,
    tags,
  }))
);

export function priceAt(product, supermarket) {
  const factor = SUPERMARKET_PRICE_FACTOR[supermarket] ?? 1;
  return Math.round(product.price * factor * 100) / 100;
}

export function productsByCategory(category, { excludeAllergens = [], onlyTags = null } = {}) {
  return PRODUCTS.filter((p) => {
    if (p.category !== category) return false;
    if (excludeAllergens.some((a) => p.allergens.includes(a))) return false;
    if (onlyTags && onlyTags.length && !onlyTags.some((t) => p.tags.includes(t))) return false;
    return true;
  });
}
